# [ghi chú] BẰNG số trong chay_thu/giao_dien/muc_toi_da.py (RAO_AI_*). 2 lần gọi = 1 + 1 lần sửa khuôn đầu ra (output_type).
RAO_AI_LUAT_TOI_DA, RAO_AI_TIN_BYTE, RAO_AI_RA_MOT_LAN, RAO_AI_LAN_GOI = 5, 64_000, 4_000, 2
GUARDRAIL_CHECK_SYSTEM_PROMPT = """
You are a helpful assistant that performs guardrail checks for an organization.

You are given content and a guardrail configuration. The content may be:
- An input prompt provided by a user
- Output content generated by an LLM
- Content from other sources

Your task is to evaluate whether the content adheres to the specified guardrail configuration.

You will be given:
    Content: ...
    Guardrail Configuration: ...

The response format must be a JSON object with the following fields:
    reason: str - Explanation of why the content passed or failed the guardrail check, should be a single sentence that can be used to explain the result to the user.
    score: int - A numerical score from 0 to 100 indicating adherence to the guardrail:
        - 0 = lowest adherence (complete violation)
        - 100 = highest adherence (fully compliant)
        - Scores between 0-100 represent varying degrees of adherence

IMPORTANT:
    - Respond with the JSON object only
    - The response must be loadable by json.loads() in Python
    - Do not add any other text, comments, or markdown formatting to the response
    - This is extremely important for proper parsing
"""

GUARDRAIL_CHECK_USER_PROMPT = """
Content: {content}

Guardrail Configuration: {guardrail_configuration}
"""


class CustomGuardrailCheckService:
    """
    Service for running custom guardrail checks.
    """

    _GUARDRAIL_CHECK_PASS_THRESHOLD = 50

    def __init__(self):
        """
        Initialize the custom guardrail check service.

        Parameters
        ----------
        None

        Returns
        -------
        None
        """
        self.guardrails_service = GuardrailsService()

    async def run_custom_guardrail_checks(
        self, orgid: str, user_token: str, guardrail_ids: list[str], content: str
    ) -> list[dict[str, Any]]:
        """
        Run guardrail checks on the provided content using specified guardrails.

        Parameters
        ----------
        orgid : str
            Organization ID for which guardrail checks will be performed.
        user_token : str
            Authentication token for the user making the request.
        guardrail_ids : list[str]
            List of guardrail IDs to check the content against.
        content : str
            The text content to be checked against the guardrails.

        Returns
        -------
        results : list[dict[str, Any]]
            A list of guardrail check results, each containing check status,
            reason for pass/fail, and other relevant information.

        Notes
        -----
        This method performs the following steps:
        1. Fetches guardrail configurations for the provided guardrail IDs
        2. Initializes an AI agent to perform the checks
        3. Runs the checks in parallel using asyncio
        4. Processes and formats the results
        5. Returns the results in a standardized format

        The method handles errors at multiple levels:
        - Errors fetching individual guardrails
        - Errors running individual guardrail checks
        - Global errors affecting the entire process

        Examples
        --------
        ```
        service = CustomGuardrailCheckService(orgid="org-123", user_token="token-abc")
        results = await service.run_custom_guardrail_checks(
            orgid="org-123",
            user_token="token-abc",
            guardrail_ids=["guardrail-1", "guardrail-2"],
            content="This is the content to check."
        )
        ```
        """
        try:
            # fetch all guardrails
            # NOTE: assumption - guardrails ids are not duplicated, guardrail ids are valid for the organization
            guardrail_id_to_guardrail = {}
            guardrail_check_results = {}
            guardrail_fetch_tasks = [
                self.guardrails_service.get_guardrail(
                    orgid=orgid,
                    guardrail_id=guardrail_id,
                    env=None,
                    user_token=user_token,
                )
                for guardrail_id in guardrail_ids
            ]
            guardrail_fetch_results = await asyncio.gather(
                *guardrail_fetch_tasks, return_exceptions=True
            )
            for guardrail_id, guardrail_fetch_result in zip(
                guardrail_ids, guardrail_fetch_results
            ):
                if isinstance(guardrail_fetch_result, Exception):
                    guardrail_check_results[guardrail_id] = (
                        GuardrailCheckFailureResponseModel(
                            id=guardrail_id,
                            name="",
                            guardrail_check_status=GuardrailCheckStatus.ERROR,
                            error_message="Unable to fetch guardrail for id",
                        )
                    )
                else:
                    guardrail_fetch_result.pop("guardrail_id", None)
                    guardrail_fetch_result.pop("created_at", None)
                    guardrail_fetch_result.pop("updated_at", None)
                    guardrail_fetch_result.pop("orgid", None)
                    guardrail_fetch_result.pop("environment", None)
                    guardrail_fetch_result.pop("active", None)
                    guardrail_fetch_result.pop("override", None)
                    guardrail_id_to_guardrail[guardrail_id] = guardrail_fetch_result

            thinking_required = True if len(content) > 5000 else False
            model_settings = (
                {
                    "thinking": {"type": "enabled", "budget_tokens": 20000},
                    "timeout": 600,
                }
                if thinking_required
                else {"thinking": {"type": "disabled"}, "timeout": 600}
            )

            class GuardrailCheckAgentResponse(BaseModel):
                reason: str
                score: int

            # [ghi chú] Rào chế độ AI: trần CỨNG để giữ chỗ tiền (muc_toi_da.py RAO_AI_*). Vượt ⇒ TỪ CHỐI cả
            # khối (không cắt: kiểm thiếu nội dung = cho qua phần chưa kiểm). Đo byte UTF-8 của chính chuỗi gửi đi (format chèn thẳng, không mã hoá).
            if len(guardrail_id_to_guardrail) > RAO_AI_LUAT_TOI_DA:
                raise ValueError(f"Rào chắn AI: tối đa {RAO_AI_LUAT_TOI_DA} luật mỗi khối (nhận {len(guardrail_id_to_guardrail)}).")
            # run custom guardrail checks
            # [VÁ 11 chay_thu 06/11/2026 — A; bản đồ "tái tạo đầy đủ" dòng 1] rào chắn GHI CỨNG Claude Sonnet 4.6 ⇒ máy chỉ có khoá OpenAI,
            # User chỉ dùng gpt-6-luna ⇒ đổi như vá 9 (get_openai_model_for_agent_node). model_settings {"thinking": …} là khoá riêng của
            # Anthropic ⇒ bỏ (biến vẫn tính để logic khác không đổi). Logic chấm 0–100, ngưỡng 50 giữ NGUYÊN.
            from ai.agentic.models.openai import get_openai_model_for_agent_node
            from core.config.ai.openai import OpenAIModels

            _ = model_settings
            # [ghi chú] file mô hình khối bảo Claude ⇒ Rào chế độ AI chạy Claude qua cổng AI (mức suy luận theo file / bảng cổng —
            # không gửi "thinking" kiểu cũ của bản gốc). Chạy Claude: KHÔNG gửi max_tokens nhỏ, KHÔNG trần token đầu ra (User 19/11 "bỏ trần … max token");
            # GIỮ số lần gọi (1 + 1 lần sửa khuôn) và rào ≤ 5 luật; rào cỡ tin 64.000 byte chỉ còn cho luna (bản 2, xem dưới). File trống ⇒ luna y như trước.
            from workflow.node.base.agent.model_resolution import chay_thu_loi_ro_nguoi_gac as _loi_ro
            from workflow.node.base.agent.model_resolution import chay_thu_mo_hinh_nguoi_gac

            _claude = await chay_thu_mo_hinh_nguoi_gac("guardrails_node", orgid, {"timeout": 600})
            # [ghi chú] rào cỡ tin gửi (≤ 64.000 byte) CHỈ còn cho tuyến tính trần tiền (luna); chạy Claude: không rào cỡ — nhà cung cấp
            # từ chối / quá giờ thì lời báo rõ ở dưới, luật đó ghi ERROR (khối không cho qua). Giữ: ≤ 5 luật, số lần gọi.
            _co_tin = {gid: len(GUARDRAIL_CHECK_USER_PROMPT.format(content=content, guardrail_configuration=_cfg).encode()) for gid, _cfg in guardrail_id_to_guardrail.items()}
            if not _claude:
                for _n in _co_tin.values():
                    if _n > RAO_AI_TIN_BYTE:
                        raise ValueError(f"Rào chắn AI: tin gửi {_n} byte vượt trần {RAO_AI_TIN_BYTE} — không cắt (phần cắt sẽ không được kiểm).")
            if _claude:
                _mo_hinh = _claude[0]
                _goi = {"usage_limits": UsageLimits(request_limit=RAO_AI_LAN_GOI)}
            else:
                _mo_hinh = get_openai_model_for_agent_node(
                    OpenAIModels.GPT_6_LUNA,
                    api_key=await resolve_api_key_for_provider(Provider.OPENAI, orgid),
                )
                _goi = {"model_settings": {"max_tokens": RAO_AI_RA_MOT_LAN},   # [va_muc_toi_da_r2]
                        "usage_limits": UsageLimits(request_limit=RAO_AI_LAN_GOI, output_tokens_limit=RAO_AI_LAN_GOI * RAO_AI_RA_MOT_LAN)}
            logger.info("[NGUOI_GAC_MO_HINH] khoi=guardrails_node mo_hinh=%s", _claude[1] if _claude else "gpt-6-luna")
            agent = Agent(
                model=_mo_hinh,
                system_prompt=GUARDRAIL_CHECK_SYSTEM_PROMPT,
                output_type=GuardrailCheckAgentResponse,
            )

            tasks = [
                agent.run(
                    GUARDRAIL_CHECK_USER_PROMPT.format(
                        content=content,
                        guardrail_configuration=guardrail_configuration,
                    ),
                    **_goi,
                )
                for guardrail_configuration in guardrail_id_to_guardrail.values()
            ]
            responses = await asyncio.gather(*tasks, return_exceptions=True)
            for guardrail_id, guardrail_check_result in zip(
                guardrail_id_to_guardrail.keys(), responses
            ):
                if isinstance(guardrail_check_result, Exception):
                    guardrail_check_results[guardrail_id] = (
                        GuardrailCheckFailureResponseModel(
                            id=guardrail_id,
                            name=guardrail_id_to_guardrail[guardrail_id].get(
                                "name", ""
                            ),
                            guardrail_check_status=GuardrailCheckStatus.ERROR,
                            error_message=_loi_ro(guardrail_check_result, "Rào chế độ AI", _co_tin.get(guardrail_id, 0)) or "Unable to run guardrail check",
                        )
                    )
                else:
                    try:
                        guardrail_check_result_output: GuardrailCheckAgentResponse = (
                            guardrail_check_result.output
                        )
                        guardrail_check_results[guardrail_id] = (
                            GuardrailCheckSuccessResponseModel(
                                id=guardrail_id,
                                name=guardrail_id_to_guardrail[guardrail_id].get(
                                    "name", ""
                                ),
                                guardrail_check_status=GuardrailCheckStatus.SUCCESS,
                                reason=guardrail_check_result_output.reason,
                                override=guardrail_id_to_guardrail[guardrail_id].get(
                                    "override", False
                                ),
                                guardrail_passed=guardrail_check_result_output.score
                                >= self._GUARDRAIL_CHECK_PASS_THRESHOLD,
                            )
                        )
                    except Exception as e:
                        capture_exception(e)
                        logger.error(
                            f"Failed to run guardrail check for guardrail id: {guardrail_id} and error: {str(e)}"
                        )
                        guardrail_check_results[guardrail_id] = (
                            GuardrailCheckFailureResponseModel(
                                id=guardrail_id,
                                name=guardrail_id_to_guardrail[guardrail_id].get(
                                    "name", ""
                                ),
                                guardrail_check_status=GuardrailCheckStatus.ERROR,
                                error_message="Unable to run guardrail check",
                            )
                        )

            return [
                guardrail_check_results[guardrail_id].model_dump()
                for guardrail_id in guardrail_ids
            ]

        except Exception as e:
            capture_exception(e)
            logger.error(f"Failed to run custom guardrail checks: {str(e)}")
            raise e
