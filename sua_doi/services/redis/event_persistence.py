"""Persist workflow events to Postgres for replay.

The agentic-backend already publishes per-session workflow events on the
``agentic_backend_{session_id}`` Redis pub/sub channel for live WebSocket
streaming. This module mirrors that stream into the existing
:class:`db.models.workflow_event.WorkflowEvent` table so the events are
**replayable after the fact** - which the A2A gateway needs for the
``get_workflow_events`` and ``get_workflow_chain_of_thought`` skills (the
external A2A client may not be holding a live SSE subscription when the
events are emitted, and may correlate days later).

Most events arrive through the Redis subscriber below. Contract-critical
events such as ``run_started`` may also call :func:`persist_workflow_event`
before publication, closing the interval where the live event has already
passed but its asynchronous durable copy is not visible yet. Both paths use
the same idempotent upsert.

Architecture
------------

A long-running asyncio task subscribes to ``agentic_backend_*`` via Redis
``psubscribe``. For each message:

1. Parse the channel name back to a ``session_id``.
2. Decode the JSON payload.
3. Call the shared durable writer, which looks up ``workflow_run.id``.
4. Insert a ``WorkflowEvent`` row, **deduplicated by ``event_id``** so
   multiple replicas of the API/worker can all run this loop without
   producing duplicate rows. We use ``INSERT ... ON CONFLICT (id)
   DO NOTHING``, where ``id`` is set to the payload's ``event_id`` (a UUID
   already generated by every event Pydantic model).

Channels we ignore
------------------

The ``agentic_backend_`` Redis prefix is shared with non-workflow channels
(``chat_state_notify:...``, ``workflow:interrupt:...``). We filter to
"workflow status" channels only, which after stripping the prefix look
like a bare ``session_id`` (alphanumerics + ``_-``, no ``:``).
"""

from __future__ import annotations

import asyncio
import json
import logging
import re
from datetime import datetime, timezone
from typing import Optional
from uuid import UUID, uuid4

from sentry_sdk import capture_exception
from sqlalchemy import select
from sqlalchemy.dialects.postgresql import insert as pg_insert

from db.models.workflow_event import WorkflowEvent
from db.models.workflow_run import WorkflowRun
from db.session import async_session_factory
from services.redis.client import RedisServiceSingleton

logger = logging.getLogger(__name__)


REDIS_PREFIX = "agentic_backend_"

# After stripping the prefix, a workflow-status channel is a bare session_id:
# letters, digits, underscore, dash. This excludes auxiliary channels like
# `agentic_backend_chat_state_notify:...` and `agentic_backend_workflow:interrupt:...`
# which contain colons.
_SESSION_ID_RE = re.compile(r"^[A-Za-z0-9_\-]+$")


class WorkflowEventPersister:
    """Subscribe to all ``agentic_backend_*`` Redis channels and persist
    each emitted event to the ``workflow_event`` Postgres table.

    Multi-replica safety:

      * The actual ``_persist`` upsert is idempotent via the
        ``ON CONFLICT (id) DO NOTHING`` clause -- so if two replicas
        ever DID write the same event, the second loses cleanly.
      * BUT in a multi-replica deploy every pod would otherwise subscribe
        to the same Redis pattern and do duplicate Postgres writes (N
        replicas = N writes per event = wasted Redis bandwidth + DB
        cycles).  So we run as a **single-leader** background task: each
        replica races to acquire a Redis lease via SETNX; the winner runs
        the subscriber loop and refreshes the lease.  On crash / lease
        expiry another replica picks up within ``_LEASE_TTL_SECONDS``.

    Failure modes are explicit:

      * Lease acquire fails (we're the follower) -> back off and retry.
      * Lease refresh fails (the lease expired before we noticed) ->
        abort the subscriber loop and fall back to the acquire path.
      * Redis itself is unreachable -> exponential backoff with cap;
        we never crash the agentic-backend process over this.
    """

    # Loop tuning
    _MESSAGE_POLL_TIMEOUT_SECONDS = 1.0

    # Leader-election tuning
    #
    # ``_LEASE_KEY`` is global per Redis instance (one persister per
    # deployment is correct -- a future "horizontal sharding" can
    # subdivide by, e.g., session-id hash if/when one persister can't
    # keep up).
    _LEASE_KEY: str = "agentic_backend:workflow_event_persister:leader"
    # [ghi chú] 30 ⇒ 120: Redis tính hạn EX theo GIỜ ĐỒNG HỒ, gia hạn ngủ theo đồng hồ ĐƠN ĐIỆU (asyncio.sleep);
    # giờ máy ảo Docker / WSL NHẢY (bước lùi 12,1 s trong log ab-api 04:34:47 UTC 18/11) ⇒ khoá hết hạn trước lần gia hạn ⇒ thoát vai ⇒ đóng pubsub
    # ⇒ sự kiện phát trong khe bị MẤT (phiên 4d741c6c mất 2 node_result). Bộ chạy thử chỉ 1 bản ab-api ⇒ TTL dài không làm chậm chuyển vai.
    # Biên chịu giờ nhảy: 120 − 10 = 110 s (trước 20 s). Bản gốc: mã nguồn nền …/services/redis/event_persistence.py (3a74fb63).
    _LEASE_TTL_SECONDS: int = 120
    # Refresh well before TTL to absorb clock skew + pause-the-world GC.
    _LEASE_REFRESH_INTERVAL_SECONDS: float = 10.0
    # Follower retry-acquire backoff (seconds).
    _FOLLOWER_RETRY_SECONDS: float = 5.0

    def __init__(self) -> None:
        self._redis = RedisServiceSingleton()
        # Identify this replica in the leader value so logs + `redis-cli
        # GET <key>` calls show *who* is leading.  POD_NAME is the
        # k8s-standard env var; falls back to a uuid4 for non-k8s
        # environments.
        import os
        import uuid as _uuid

        self._replica_id = (
            os.environ.get("POD_NAME")
            or os.environ.get("HOSTNAME")
            or str(_uuid.uuid4())[:8]
        )

    async def run(self) -> None:
        """Run the subscriber loop forever -- single-leader across replicas.

        Outer loop: race for the lease.  Inner loop: subscribe + persist.
        Cancellable via ``task.cancel()`` at any point.
        """

        while True:
            try:
                acquired = await self._try_acquire_lease()
                if not acquired:
                    # Not the leader.  Wait + retry.
                    await asyncio.sleep(self._FOLLOWER_RETRY_SECONDS)
                    continue
                logger.info(
                    "workflow_event persister LEADER on replica=%s (lease=%ss)",
                    self._replica_id,
                    self._LEASE_TTL_SECONDS,
                )
                await self._run_as_leader()
            except asyncio.CancelledError:
                # Outer-loop cancellation: drop the lease so a peer can
                # take over immediately instead of waiting for TTL.
                logger.info("workflow_event persister cancelled")
                await self._release_lease_best_effort()
                raise
            except Exception as e:  # noqa: BLE001 - guard rail
                # Any unhandled error: release the lease (don't sit on
                # it) and keep the outer loop alive so this replica can
                # try again on the next iteration.
                capture_exception(e)
                logger.exception(
                    "workflow_event persister crashed: %s -- "
                    "releasing lease + retrying",
                    e,
                )
                await self._release_lease_best_effort()
                await asyncio.sleep(self._FOLLOWER_RETRY_SECONDS)

    async def _run_as_leader(self) -> None:
        """Hold the lease + run the subscribe-and-persist loop."""

        client = self._redis._get_client()  # noqa: SLF001 - shared singleton
        pubsub = client.pubsub()
        refresh_task: Optional[asyncio.Task] = None
        try:
            await pubsub.psubscribe(f"{REDIS_PREFIX}*")
            logger.info(
                "workflow_event persister subscribed to pattern %s*",
                REDIS_PREFIX,
            )
            # Start the heartbeat to keep the lease alive while we
            # process messages.  If the heartbeat fails (lease lost),
            # it cancels the parent task so the leader loop exits and
            # the outer ``run()`` re-acquires.
            refresh_task = asyncio.create_task(self._refresh_lease_loop())

            while True:
                message = await pubsub.get_message(
                    ignore_subscribe_messages=True,
                    timeout=self._MESSAGE_POLL_TIMEOUT_SECONDS,
                )
                # If the refresh task died -- e.g. we lost the lease --
                # bail out so the outer loop re-races.
                if refresh_task.done():
                    err = refresh_task.exception()
                    if err is not None:
                        logger.warning(
                            "workflow_event persister lease refresh failed: %s "
                            "-- falling back to follower",
                            err,
                        )
                    else:
                        logger.warning(
                            "workflow_event persister lease lost -- "
                            "falling back to follower"
                        )
                    return
                if message is None:
                    continue
                await self._handle_message(message)
        finally:
            if refresh_task is not None and not refresh_task.done():
                refresh_task.cancel()
                try:
                    await refresh_task
                except (asyncio.CancelledError, Exception):  # noqa: BLE001
                    pass
            try:
                await pubsub.aclose()
            except Exception:  # noqa: BLE001 - best effort
                pass

    async def _try_acquire_lease(self) -> bool:
        """SETNX the lease key with a TTL.  Returns True iff we got it."""

        try:
            client = self._redis._get_client()  # noqa: SLF001
            # ``SET key value NX EX <ttl>`` is the canonical atomic lease.
            ok = await client.set(
                self._LEASE_KEY,
                self._replica_id,
                ex=self._LEASE_TTL_SECONDS,
                nx=True,
            )
            return bool(ok)
        except Exception as e:  # noqa: BLE001
            logger.warning(
                "workflow_event persister lease acquire failed (Redis "
                "unreachable?): %s",
                e,
            )
            # Don't crash -- treat as "not the leader" so the outer loop
            # backs off and retries.
            return False

    async def _refresh_lease_loop(self) -> None:
        """Heartbeat the lease while we hold it.  Exits if the lease is lost."""

        client = self._redis._get_client()  # noqa: SLF001
        while True:
            await asyncio.sleep(self._LEASE_REFRESH_INTERVAL_SECONDS)
            try:
                # Only refresh if we're still the value-holder.  Avoids
                # accidentally extending a peer's lease if a clock-skew
                # weirdness let two replicas briefly think they were
                # leader.
                current = await client.get(self._LEASE_KEY)
                if isinstance(current, bytes):
                    current = current.decode("utf-8", errors="ignore")
                if current != self._replica_id:
                    logger.info(
                        "workflow_event persister lease no longer ours "
                        "(value=%r, expected=%r) -- yielding leadership",
                        current,
                        self._replica_id,
                    )
                    return
                # Extend.  PEXPIRE would also work; EXPIRE is fine here.
                await client.expire(self._LEASE_KEY, self._LEASE_TTL_SECONDS)
            except Exception as e:  # noqa: BLE001
                logger.warning(
                    "workflow_event persister lease refresh error: %s "
                    "-- yielding leadership",
                    e,
                )
                return

    async def _release_lease_best_effort(self) -> None:
        """Drop the lease on graceful shutdown / crash so a peer can pick up."""

        try:
            client = self._redis._get_client()  # noqa: SLF001
            current = await client.get(self._LEASE_KEY)
            if isinstance(current, bytes):
                current = current.decode("utf-8", errors="ignore")
            if current == self._replica_id:
                await client.delete(self._LEASE_KEY)
        except Exception:  # noqa: BLE001
            pass

    async def _handle_message(self, message: dict) -> None:
        """Parse one Redis message and persist it. Logs+swallows errors so
        a single malformed event cannot kill the loop."""

        try:
            session_id = self._extract_session_id(message.get("channel"))
            if not session_id:
                return  # Non-workflow channel (chat state, interrupt, etc.)

            raw_data = message.get("data")
            if not raw_data:
                return
            try:
                payload = json.loads(raw_data)
            except (TypeError, json.JSONDecodeError):
                logger.debug(
                    "workflow_event persister skipping non-JSON payload on %s",
                    session_id,
                )
                return
            if not isinstance(payload, dict):
                return
            if payload.get("ephemeral"):
                # High-frequency UI deltas (e.g. interim live-transcript
                # phrases) that the next message replaces. Persisting them
                # costs a SELECT + INSERT each, through a single-leader
                # persister, for a row nothing ever reads back.
                return

            await self._persist(session_id, payload)
        except Exception as e:
            capture_exception(e)
            logger.warning("workflow_event persister handler error: %s", e)

    @staticmethod
    def _extract_session_id(channel) -> Optional[str]:
        """Strip ``agentic_backend_`` and reject non-session-id channels."""

        if not channel:
            return None
        if isinstance(channel, bytes):
            channel = channel.decode("utf-8", errors="ignore")
        if not channel.startswith(REDIS_PREFIX):
            return None
        rest = channel[len(REDIS_PREFIX) :]
        if ":" in rest:
            return None
        if not _SESSION_ID_RE.match(rest):
            return None
        return rest

    async def _persist(self, session_id: str, payload: dict) -> bool:
        """Resolve and upsert one event through the shared durable writer."""

        return await persist_workflow_event(session_id, payload)

    @staticmethod
    def _coerce_uuid(value) -> Optional[UUID]:
        if value is None:
            return None
        if isinstance(value, UUID):
            return value
        try:
            return UUID(str(value))
        except (ValueError, TypeError):
            return None

    @staticmethod
    def _coerce_timestamp(value) -> datetime:
        """Parse an ISO-8601 timestamp from the payload. Falls back to now."""

        if isinstance(value, datetime):
            return value if value.tzinfo else value.replace(tzinfo=timezone.utc)
        if isinstance(value, str) and value:
            normalized = value.replace("Z", "+00:00")
            try:
                parsed = datetime.fromisoformat(normalized)
                if parsed.tzinfo is None:
                    parsed = parsed.replace(tzinfo=timezone.utc)
                return parsed
            except ValueError:
                pass
        return datetime.now(timezone.utc)

    @staticmethod
    def _coerce_node_id(value) -> Optional[str]:
        if value is None:
            return None
        # workflow_event.node_instance_id is String(100); truncate defensively.
        return str(value)[:100]


async def persist_workflow_event(session_id: str, payload: dict) -> bool:
    """Durably upsert one workflow event, independently of Redis pub/sub.

    Most events reach this function through the single-leader Redis subscriber.
    A small number of contract-critical events may call it before publishing so
    a subscriber that attaches just after publication can always recover them
    from backfill. The payload's event id makes both paths idempotent.

    Returns ``True`` after the run was resolved and the transaction committed;
    ``False`` when the run is not visible yet or the write fails. Failures stay
    non-fatal so observability cannot stop workflow execution.
    """

    event_id = WorkflowEventPersister._coerce_uuid(payload.get("event_id")) or uuid4()
    event_type = str(payload.get("event_type") or "unknown")[:50]
    timestamp = WorkflowEventPersister._coerce_timestamp(payload.get("timestamp"))
    node_instance_id = WorkflowEventPersister._coerce_node_id(payload.get("node_id"))

    try:
        factory = async_session_factory(use_fresh_engine=False)
        async with factory() as session:
            run_id_stmt = select(WorkflowRun.id).where(
                WorkflowRun.session_id == session_id
            )
            result = await session.execute(run_id_stmt)
            run_id = result.scalar_one_or_none()
            if run_id is None:
                logger.debug(
                    "workflow_event persister: no workflow_run for session %s yet, "
                    "skipping",
                    session_id,
                )
                return False

            insert_stmt = (
                pg_insert(WorkflowEvent)
                .values(
                    id=event_id,
                    run_id=run_id,
                    node_instance_id=node_instance_id,
                    event_type=event_type,
                    event_data=payload,
                    timestamp=timestamp,
                )
                .on_conflict_do_nothing(index_elements=["id"])
            )
            await session.execute(insert_stmt)
            await session.commit()
            return True
    except Exception as e:
        capture_exception(e)
        logger.warning(
            "workflow_event persister failed for session %s event %s: %s",
            session_id,
            event_id,
            e,
        )
        return False
